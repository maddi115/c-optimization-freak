// embed.c - bakes the built page (ui/dist) into C source, so the release program is one file.
// usage: embed ../ui/dist src/generated/assets.c
#include <dirent.h>
#include <stdio.h>
#include <string.h>
#include <sys/stat.h>

static FILE *out;
static char paths[64][256];
static long sizes[64];
static int n = 0;

static void add(const char *disk, const char *url) {
    FILE *f = fopen(disk, "rb");
    if (!f || n == 64) { if (f) fclose(f); return; }
    fprintf(out, "static const unsigned char file%d[] = {", n);
    int ch;
    long size = 0;
    while ((ch = fgetc(f)) != EOF) fprintf(out, "%s%d,", size++ % 24 ? "" : "\n  ", ch);
    fprintf(out, "0\n};\n\n");
    fclose(f);
    snprintf(paths[n], sizeof paths[n], "%s", url);
    sizes[n++] = size;
}

static void walk(const char *dir, const char *prefix, int depth) {
    DIR *d = opendir(dir);
    if (!d) return;
    struct dirent *e;
    while ((e = readdir(d))) {
        if (e->d_name[0] == '.') continue;
        char disk[1024], url[256];
        if ((size_t)snprintf(disk, sizeof disk, "%s/%s", dir, e->d_name) >= sizeof disk) continue;
        if ((size_t)snprintf(url, sizeof url, "%s/%s", prefix, e->d_name) >= sizeof url) continue;
        struct stat st;
        if (stat(disk, &st) < 0) continue;
        if (S_ISDIR(st.st_mode)) { if (depth < 1) walk(disk, url, depth + 1); }
        else if (S_ISREG(st.st_mode)) add(disk, url);
    }
    closedir(d);
}

int main(int argc, char **argv) {
    if (argc != 3) { fprintf(stderr, "usage: %s dist_dir out.c\n", argv[0]); return 1; }
    out = fopen(argv[2], "w");
    if (!out) { perror(argv[2]); return 1; }
    fprintf(out, "// GENERATED by tools/embed.c from %s. Do not edit.\n#include \"http.h\"\n\n", argv[1]);
    walk(argv[1], "", 0);
    fprintf(out, "const EmbeddedFile embedded_files[] = {\n");
    for (int i = 0; i < n; i++) fprintf(out, "  {\"%s\", file%d, %ld},\n", paths[i], i, sizes[i]);
    fprintf(out, "  {0, 0, 0}\n};\nconst int embedded_count = %d;\n", n);
    fclose(out);
    int has_index = 0;
    for (int i = 0; i < n; i++) has_index |= !strcmp(paths[i], "/index.html");
    if (!has_index) { fprintf(stderr, "no index.html in %s: run `npm run build` in ui/ first\n", argv[1]); return 1; }
    printf("embedded %d page files into %s\n", n, argv[2]);
    return 0;
}
